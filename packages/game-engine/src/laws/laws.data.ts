import type { LawCategoryDefinition, LawOptionDefinition } from './types';

type Opt = Omit<LawOptionDefinition, 'economy' | 'budget' | 'pops' | 'groups' | 'issues'> &
  Partial<Pick<LawOptionDefinition, 'economy' | 'budget' | 'pops' | 'groups' | 'issues'>>;

function opt(o: Opt): LawOptionDefinition {
  return { economy: {}, budget: {}, pops: {}, groups: {}, issues: {}, ...o };
}

type Cat = Omit<LawCategoryDefinition, 'constitutional'>;

/** `constitutional` decorre do instrumento: só a PEC exige 3/5 em dois turnos. */
function category(c: Cat): LawCategoryDefinition {
  return { ...c, constitutional: c.instrument === 'pec' };
}

