export function getLawCategory(id: string): LawCategoryDefinition | undefined {
  return LAW_CATEGORIES.find((c) => c.id === id);
}

export function getLawOption(
  categoryId: string,
  optionId: string,
): LawOptionDefinition | undefined {
  return getLawCategory(categoryId)?.options.find((o) => o.id === optionId);
}

export function defaultLaws(): Record<string, string> {
  return Object.fromEntries(LAW_CATEGORIES.map((c) => [c.id, c.defaultOptionId]));
}
